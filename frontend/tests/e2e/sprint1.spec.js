test('A4: credenciales incorrectas, sesión restaurada y cierre', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Correo electrónico o usuario').fill('operador')
  await page.getByLabel('Contraseña', { exact: true }).fill('incorrecta')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('incorrectos')
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Mostrar contraseña' }).click()
  await expect(page.getByLabel('Contraseña', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Gestionar menú' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Gestionar menú' })).toBeVisible()
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Qué bueno verte' })).toBeVisible()
})
