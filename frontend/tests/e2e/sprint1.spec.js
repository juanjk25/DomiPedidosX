import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const password = 'ClavePrueba-489!'
async function login(page, username = 'operador') {
  await page.goto('/login')
  await page.getByLabel('Correo electrónico o usuario').fill(username)
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: username === 'operador' ? 'Gestionar menú' : '¿Qué se te antoja hoy?' })).toBeVisible()
}
test.beforeEach(async ({ page }) => {
  // Pruebas deterministas: imágenes externas y fuentes no son dependencias de negocio.
  await page.route('https://placehold.co/**', route => route.abort())
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
})
