test('A6: error de red y bloqueo de doble envío', async ({ page }) => {
  let requests = 0
  await page.route('**/api/auth/password-reset/', async route => { requests++; await new Promise(resolve => setTimeout(resolve, 250)); await route.abort() })
  await page.goto('/recuperar-contrasena')
  await page.getByLabel('Correo electrónico registrado').fill('cliente@example.org')
  await page.getByRole('button', { name: 'Enviar enlace' }).click()
  await expect(page.getByRole('button', { name: 'Enviando…' })).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('conectar con el servidor')
  expect(requests).toBe(1)
})
test('A6: enlace real cambia contraseña y permite iniciar sesión', async ({ page }) => {
  const { uid, token } = JSON.parse(readFileSync('.e2e-data/reset-link.json', 'utf8'))
  await page.goto(`/restablecer-contrasena?uid=${uid}&token=${token}`)
  await page.getByLabel('Nueva contraseña', { exact: true }).fill('NuevaClaveSegura-953!')
  await page.getByLabel('Confirmar nueva contraseña').fill('NoCoincide-953!')
  await page.getByRole('button', { name: 'Guardar nueva contraseña' }).click()
  await expect(page.getByRole('alert')).toContainText('no coinciden')
  await page.getByLabel('Confirmar nueva contraseña').fill('NuevaClaveSegura-953!')
  await page.getByRole('button', { name: 'Guardar nueva contraseña' }).click()
  await expect(page.getByRole('status')).toContainText('actualizó correctamente')
  await page.getByRole('button', { name: 'Volver a iniciar sesión' }).click()
  await page.getByLabel('Correo electrónico o usuario').fill('reset@example.org')
  await page.getByLabel('Contraseña', { exact: true }).fill('NuevaClaveSegura-953!')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: '¿Qué se te antoja hoy?' })).toBeVisible()
})
