test('B4 B5 B6 B8: crear, editar, cancelar desactivación, desactivar y reflejarlo en cliente', async ({ page, browser }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await page.getByRole('button', { name: 'Crear producto' }).click()
  await page.getByRole('button', { name: 'Crear producto', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Revisa los campos')
  await page.getByLabel('Nombre del producto').fill('Pizza de prueba E2E')
  await page.getByLabel('Código de barras').fill('E2E-001')
  await page.getByLabel('Precio de venta').fill('25500.50')
  await page.getByLabel('Categoría', { exact: false }).selectOption({ label: 'Comida' })
  await page.getByLabel('Tiempo de preparación').fill('18')
  await page.getByLabel('URL de la imagen').fill('https://placehold.co/600x400/png?text=Pizza')
  await page.screenshot({ path: 'test-results/qa-producto-form.png', fullPage: true })
  await page.getByRole('button', { name: 'Crear producto', exact: true }).click()
  await expect(page.getByText('Producto creado y asociado a la sede.', { exact: true })).toBeVisible()
  let card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Pizza de prueba E2E', exact: true }) })
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.getByLabel('Nombre del producto').fill('Pizza editada E2E')
  await page.getByLabel('Precio de venta').fill('28000')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByText('Producto actualizado.', { exact: true })).toBeVisible()
  await page.reload()
  card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Pizza editada E2E', exact: true }) })
  await expect(card).toContainText('28.000')
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5173' })
  const customer = await context.newPage()
  await customer.route('https://placehold.co/**', route => route.abort())
  await login(customer, 'cliente@example.org')
  await expect(customer.getByRole('heading', { name: 'Pizza editada E2E', exact: true })).toBeVisible()
  await card.getByRole('button', { name: 'Desactivar', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(card.getByText('Activo', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: 'Desactivar', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar desactivación' }).click()
  await expect(card.getByText('Inactivo', { exact: true })).toBeVisible()
  // Otro dispositivo/contexto: el sondeo real sincroniza el menú sin recargar.
  await expect(customer.getByRole('heading', { name: 'Pizza editada E2E', exact: true })).toHaveCount(0, { timeout: 20000 })
  await page.screenshot({ path: 'test-results/qa-gestion-menu.png', fullPage: true })
  expect(errors).toEqual([])
  await context.close()
})
